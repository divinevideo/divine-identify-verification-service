// Builds the nostr-tools code the landing page runs in the browser into one
// module the verifier serves itself, so the page runs no third-party script.
//
//   npm run build:vendor   rebuild public/vendor/nostr-tools.mjs and src/generated/vendor.ts
//   npm run check:vendor   fail if the committed files differ from a fresh build
//
// Both files are committed. CI runs the check, so the committed module is
// provably what esbuild makes from the versions pinned in package-lock.json;
// nobody has to read minified code to trust it. Upgrading nostr-tools means
// bumping its exact version, `npm install`, then `npm run build:vendor`.
//
// --root <dir> writes or checks the files under another directory (for tests).
import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const REPO = fileURLToPath(new URL('..', import.meta.url))
const MODULE_FILE = 'public/vendor/nostr-tools.mjs'
const ADDRESS_FILE = 'src/generated/vendor.ts'

// Exactly the functions the page calls, grouped the way it calls them.
const ENTRY = `
import { BunkerSigner, createNostrConnectURI, parseBunkerInput } from 'nostr-tools/nip46'
import { generateSecretKey, getPublicKey, verifyEvent } from 'nostr-tools/pure'
export const nip46 = { BunkerSigner, createNostrConnectURI, parseBunkerInput }
export const pure = { generateSecretKey, getPublicKey, verifyEvent }
`

async function buildFiles() {
  const { version } = JSON.parse(await readFile(join(REPO, 'node_modules/nostr-tools/package.json'), 'utf8'))
  const result = await build({
    stdin: { contents: ENTRY, resolveDir: REPO, sourcefile: 'nostr-tools-entry.mjs' },
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    write: false,
    // Keeps the dependencies' license notices, at the end of the file.
    legalComments: 'eof',
    banner: { js: `// nostr-tools ${version}, built by scripts/build-browser-vendor.mjs. Do not edit.` },
  })
  const module = result.outputFiles[0].text
  const hash = createHash('sha256').update(module).digest('hex').slice(0, 12)
  const address = [
    '// Generated by scripts/build-browser-vendor.mjs. Do not edit; run `npm run build:vendor`.',
    '// Where the landing page loads nostr-tools from. The query is the start of',
    '// the file\'s SHA-256, so a new build gets a new address and browsers fetch it.',
    `export const NOSTR_TOOLS_MODULE_PATH = '/${MODULE_FILE.replace(/^public\//, '')}?v=${hash}'`,
    '',
  ].join('\n')
  return { [MODULE_FILE]: module, [ADDRESS_FILE]: address }
}

async function readIfPresent(file) {
  try {
    return await readFile(file, 'utf8')
  } catch {
    return null
  }
}

const args = process.argv.slice(2)
const rootFlag = args.indexOf('--root')
const root = rootFlag === -1 ? REPO : args[rootFlag + 1]
if (!root) throw new Error('--root needs a directory')
const files = await buildFiles()

if (args.includes('--check')) {
  const stale = []
  for (const [name, contents] of Object.entries(files)) {
    if ((await readIfPresent(join(root, name))) !== contents) stale.push(name)
  }
  if (stale.length > 0) {
    console.error(`These files differ from a fresh build: ${stale.join(', ')}. Run \`npm run build:vendor\` and commit the result.`)
    process.exit(1)
  }
} else {
  for (const [name, contents] of Object.entries(files)) {
    await mkdir(dirname(join(root, name)), { recursive: true })
    await writeFile(join(root, name), contents)
  }
}
